using System.Net;
using System.Net.Http.Json;
using System.Text.Json;
using System.Text.Json.Serialization;
using ClientPulse.Api.Analysis;
using ClientPulse.Api.Assessments;
using ClientPulse.Api.Data;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.AspNetCore.TestHost;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;

namespace ClientPulse.Tests;

// Provider behaviour through the real endpoints, with fake analyzers standing
// in for Claude. No test here makes a live API call.
[Collection(ApiCollection.Name)]
public class ProviderAnalysisEndpointsTests(ApiFactory factory)
{
    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        Converters = { new JsonStringEnumConverter() },
    };

    private readonly HttpClient _client = factory.CreateClient();

    private Task<int> CreateClientAsync() =>
        TestClients.CreateAsync(factory, TestClients.Scenario("cedar-ridge-renewal-risk"));

    private WebApplicationFactory<Program> With(ICommunicationAnalyzer analyzer) =>
        factory.WithWebHostBuilder(builder => builder.ConfigureTestServices(services =>
            services.AddSingleton(analyzer)));

    private async Task<int> AssessmentCountAsync(int clientId)
    {
        using var scope = factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<ClientPulseDbContext>();
        return await db.Assessments.CountAsync(a => a.ClientId == clientId);
    }

    [Fact]
    public async Task ActiveProvider_InTests_IsFixture()
    {
        var provider = await _client.GetFromJsonAsync<ActiveAnalysisProvider>("/api/analysis/provider", Json);

        Assert.Equal(new ActiveAnalysisProvider(AnalysisProvider.Fixture, null, null), provider);
    }

    [Fact]
    public async Task ProviderResult_IsSavedWithProvenanceAndLabelledAsAi()
    {
        var clientId = await CreateClientAsync();
        using var ai = With(new FakeProvider(request => new AnalysisCompleted(ValidResult(request))));

        var response = await ai.CreateClient().PostAsync($"/api/clients/{clientId}/assessments", null);

        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        var assessment = (await response.Content.ReadFromJsonAsync<AssessmentResponse>(Json))!;
        Assert.Equal(AnalysisSource.Anthropic, assessment.Source);
        Assert.False(assessment.IsFixture);
        Assert.Null(assessment.FixtureName);
        Assert.Equal("claude-sonnet-5-5", assessment.RequestedModel);
        Assert.Equal("claude-sonnet-5-5-synthetic-snapshot", assessment.ResponseModel);
        Assert.Equal("medium", assessment.Effort);
        Assert.StartsWith("AI-generated by claude-sonnet-5-5-synthetic-snapshot", assessment.Disclaimer);
        Assert.Equal(ReviewStatus.Unreviewed, assessment.ReviewStatus);

        var history = await _client.GetFromJsonAsync<List<AssessmentSummaryResponse>>(
            $"/api/clients/{clientId}/assessments", Json);
        Assert.Equal("claude-sonnet-5-5-synthetic-snapshot", Assert.Single(history!).ResponseModel);
    }

    [Theory]
    [InlineData(AnalysisFailureKind.InvalidOutput, HttpStatusCode.BadGateway, "provider_invalid_output")]
    [InlineData(AnalysisFailureKind.OutputTruncated, HttpStatusCode.BadGateway, "provider_output_truncated")]
    [InlineData(AnalysisFailureKind.Refused, HttpStatusCode.BadGateway, "provider_refused")]
    [InlineData(AnalysisFailureKind.Unavailable, HttpStatusCode.ServiceUnavailable, "provider_unavailable")]
    [InlineData(AnalysisFailureKind.Timeout, HttpStatusCode.GatewayTimeout, "provider_timeout")]
    [InlineData(AnalysisFailureKind.Configuration, HttpStatusCode.BadGateway, "provider_configuration_error")]
    public async Task ProviderFailure_MapsToStatus_SavesNothing_AndKeepsPreviousAssessment(
        AnalysisFailureKind kind, HttpStatusCode status, string code)
    {
        var clientId = await CreateClientAsync();
        var previous = await _client.PostAsync($"/api/clients/{clientId}/assessments", null);
        var previousId = (await previous.Content.ReadFromJsonAsync<AssessmentResponse>(Json))!.Id;
        using var failing = With(new FakeProvider(_ => new AnalysisFailed(kind)));

        var response = await failing.CreateClient().PostAsync($"/api/clients/{clientId}/assessments", null);

        Assert.Equal(status, response.StatusCode);
        var body = await response.Content.ReadAsStringAsync();
        var problem = JsonSerializer.Deserialize<ProblemDetails>(body, Json);
        Assert.Equal(code, problem?.Extensions["code"]?.ToString());
        Assert.DoesNotContain("Synthetic", body); // no communication text in errors

        Assert.Equal(1, await AssessmentCountAsync(clientId));
        var latest = await _client.GetFromJsonAsync<AssessmentResponse>(
            $"/api/clients/{clientId}/assessments/latest", Json);
        Assert.Equal(previousId, latest!.Id);
    }

    [Fact]
    public async Task ProviderEvidenceOutsideInput_Is502InvalidOutput_AndSavesNothing()
    {
        var clientId = await CreateClientAsync();
        using var invalid = With(new FakeProvider(request => new AnalysisCompleted(ValidResult(request) with
        {
            Signals = [new AnalysisSignal(SignalKind.Concern, "Cites another client.", [int.MaxValue])],
        })));

        var response = await invalid.CreateClient().PostAsync($"/api/clients/{clientId}/assessments", null);

        Assert.Equal(HttpStatusCode.BadGateway, response.StatusCode);
        var problem = await response.Content.ReadFromJsonAsync<ProblemDetails>();
        Assert.Equal(AssessmentProblems.ProviderInvalidOutputCode, problem?.Extensions["code"]?.ToString());
        Assert.Equal(0, await AssessmentCountAsync(clientId));
    }

    [Fact]
    public async Task ProviderInputOverLimit_Is422Unsupported()
    {
        var clientId = await CreateClientAsync();
        using var limited = With(new FakeProvider(_ => new AnalysisUnsupported("Synthetic limit reason.")));

        var response = await limited.CreateClient().PostAsync($"/api/clients/{clientId}/assessments", null);

        Assert.Equal(HttpStatusCode.UnprocessableEntity, response.StatusCode);
        Assert.Equal(0, await AssessmentCountAsync(clientId));
    }

    private static AnalysisResult ValidResult(AnalysisRequest request) => new(
        AnalysisSource.Anthropic,
        FixtureName: null,
        "Synthetic AI summary.",
        AttentionLevel.High,
        [new AnalysisSignal(SignalKind.Concern, "Synthetic concern.", [request.Communications[0].Id])],
        RequestedModel: "claude-sonnet-5-5",
        ResponseModel: "claude-sonnet-5-5-synthetic-snapshot",
        Effort: "medium");

    private sealed class FakeProvider(Func<AnalysisRequest, AnalyzerOutcome> respond) : ICommunicationAnalyzer
    {
        public Task<AnalyzerOutcome> AnalyzeAsync(AnalysisRequest request, CancellationToken cancellationToken) =>
            Task.FromResult(respond(request));
    }
}
