using ClientPulse.Api.Analysis;
using ClientPulse.Api.Data;
using Microsoft.EntityFrameworkCore;

namespace ClientPulse.Api.Assessments;

public enum AnalyzeStatus
{
    Created,
    ClientNotFound,
    NoCommunications,
    Unsupported,
    InvalidOutput,
    ProviderFailed,
}

public record AnalyzeResult(
    AnalyzeStatus Status,
    AssessmentResponse? Assessment = null,
    string? Reason = null,
    AnalysisFailureKind? FailureKind = null);

public enum ReviewSubmitStatus
{
    Created,
    NotFound,
    NotLatest,
    Invalid,
}

public record ReviewSubmitResult(
    ReviewSubmitStatus Status,
    ReviewResponse? Review = null,
    Dictionary<string, string[]>? Errors = null);

// Runs one synchronous analysis: load the client's communications, invoke the
// analyzer, validate its output, and insert a new assessment. Any failure
// returns before saving, so previous assessments are never changed.
public class AssessmentService(
    ClientPulseDbContext db,
    ICommunicationAnalyzer analyzer,
    TimeProvider timeProvider,
    ILogger<AssessmentService> logger)
{
    public const string FixtureDisclaimer =
        "Fixture result: predefined for a synthetic demo scenario. Not produced by AI or any real analysis.";

    public static string Disclaimer(AnalysisSource source, string? model) => source == AnalysisSource.Fixture
        ? FixtureDisclaimer
        : $"AI-generated by {model ?? "an AI model"}. May be inaccurate; review before relying on it. Synthetic data only.";

    public async Task<AnalyzeResult> AnalyzeAsync(int clientId, CancellationToken cancellationToken)
    {
        if (!await db.Clients.AnyAsync(client => client.Id == clientId, cancellationToken))
        {
            return new AnalyzeResult(AnalyzeStatus.ClientNotFound);
        }

        var communications = await db.Communications
            .AsNoTracking()
            .Where(communication => communication.ClientId == clientId)
            .OrderBy(communication => communication.OccurredAt)
            .ThenBy(communication => communication.Id)
            .Select(communication => new AnalysisCommunication(
                communication.Id,
                communication.Type,
                communication.OccurredAt,
                communication.Subject,
                communication.Body))
            .ToListAsync(cancellationToken);

        if (communications.Count == 0)
        {
            return new AnalyzeResult(AnalyzeStatus.NoCommunications);
        }

        var outcome = await analyzer.AnalyzeAsync(new AnalysisRequest(clientId, communications), cancellationToken);

        if (outcome is AnalysisUnsupported unsupported)
        {
            return new AnalyzeResult(AnalyzeStatus.Unsupported, Reason: unsupported.Reason);
        }

        if (outcome is AnalysisFailed failed)
        {
            return new AnalyzeResult(AnalyzeStatus.ProviderFailed, FailureKind: failed.Kind);
        }

        if (outcome is not AnalysisCompleted { Result: var result })
        {
            logger.LogWarning("Analyzer returned an unrecognised outcome for client {ClientId}", clientId);
            return new AnalyzeResult(AnalyzeStatus.InvalidOutput);
        }

        var inputIds = communications.Select(c => c.Id).ToHashSet();
        var errors = AssessmentOutputRules.Validate(result, inputIds);
        if (errors.Count > 0)
        {
            // Errors reference fields and ids only, never communication text.
            logger.LogWarning(
                "Rejected invalid {Source} analyzer output for client {ClientId}: {Errors}",
                result.Source,
                clientId,
                string.Join(" ", errors));

            // Invalid output from an external provider is a 502; from the
            // in-process fixture analyzer it is a 500.
            return result.Source == AnalysisSource.Fixture
                ? new AnalyzeResult(AnalyzeStatus.InvalidOutput)
                : new AnalyzeResult(AnalyzeStatus.ProviderFailed, FailureKind: AnalysisFailureKind.InvalidOutput);
        }

        var assessment = new Assessment
        {
            ClientId = clientId,
            CreatedAt = timeProvider.GetUtcNow(),
            Source = result.Source,
            FixtureName = result.FixtureName,
            RequestedModel = result.RequestedModel,
            ResponseModel = result.ResponseModel,
            Effort = result.Effort,
            Summary = result.Summary,
            AttentionLevel = result.AttentionLevel,
            InputFingerprint = InputFingerprint.Compute(communications),
            AnalyzedCommunicationIds = communications.Select(c => c.Id).ToList(),
            Signals = result.Signals
                .Select(signal => new AssessmentSignal
                {
                    Kind = signal.Kind,
                    Description = signal.Description,
                    EvidenceCommunicationIds = signal.EvidenceCommunicationIds.ToList(),
                })
                .ToList(),
        };

        db.Assessments.Add(assessment);
        await db.SaveChangesAsync(cancellationToken);

        return new AnalyzeResult(AnalyzeStatus.Created, await ToResponseAsync(assessment, cancellationToken));
    }

    // Null when the client has no assessment yet. Callers check the client exists.
    public async Task<AssessmentResponse?> GetLatestAsync(int clientId, CancellationToken cancellationToken)
    {
        var latestId = await LatestAssessmentIdAsync(clientId, cancellationToken);
        return latestId is null ? null : await GetAsync(clientId, latestId.Value, cancellationToken);
    }

    // Null when the assessment does not exist or belongs to another client.
    public async Task<AssessmentResponse?> GetAsync(int clientId, int assessmentId, CancellationToken cancellationToken)
    {
        var assessment = await db.Assessments
            .AsNoTracking()
            .SingleOrDefaultAsync(a => a.Id == assessmentId && a.ClientId == clientId, cancellationToken);

        return assessment is null ? null : await ToResponseAsync(assessment, cancellationToken);
    }

    // Newest first. Callers check the client exists.
    public async Task<List<AssessmentSummaryResponse>> GetHistoryAsync(int clientId, CancellationToken cancellationToken)
    {
        // Order before projecting: EF cannot translate ordering on members of
        // a constructor-projected record.
        var rows = await SummaryRows(db.Assessments
                .Where(a => a.ClientId == clientId)
                .OrderByDescending(a => a.CreatedAt)
                .ThenByDescending(a => a.Id))
            .ToListAsync(cancellationToken);

        var currentFingerprint = await CurrentFingerprintAsync(clientId, cancellationToken);
        var latestId = rows.FirstOrDefault()?.Id;

        return rows.Select(row => ToSummary(row, row.InputFingerprint == currentFingerprint, row.Id == latestId)).ToList();
    }

    // Each client's latest assessment, keyed by client id; clients without one
    // are absent. Two queries in total, however many clients there are.
    public async Task<Dictionary<int, AssessmentSummaryResponse>> GetLatestByClientAsync(CancellationToken cancellationToken)
    {
        var latest = db.Assessments.Where(a => !db.Assessments.Any(newer =>
            newer.ClientId == a.ClientId &&
            (newer.CreatedAt > a.CreatedAt || (newer.CreatedAt == a.CreatedAt && newer.Id > a.Id))));

        var rows = await SummaryRows(latest).ToListAsync(cancellationToken);
        if (rows.Count == 0)
        {
            return [];
        }

        var clientIds = rows.Select(row => row.ClientId).ToList();
        var communications = await db.Communications
            .AsNoTracking()
            .Where(c => clientIds.Contains(c.ClientId))
            .ToListAsync(cancellationToken);
        var fingerprints = communications
            .GroupBy(c => c.ClientId)
            .ToDictionary(group => group.Key, group => InputFingerprint.Compute(group));

        return rows.ToDictionary(
            row => row.ClientId,
            row => ToSummary(row, fingerprints.GetValueOrDefault(row.ClientId) == row.InputFingerprint, isLatest: true));
    }

    private sealed record SummaryRow(
        int Id,
        int ClientId,
        DateTimeOffset CreatedAt,
        AnalysisSource Source,
        string? FixtureName,
        string? ResponseModel,
        AttentionLevel AttentionLevel,
        string InputFingerprint,
        AssessmentReview? LatestReview);

    private IQueryable<SummaryRow> SummaryRows(IQueryable<Assessment> assessments) =>
        assessments
            .AsNoTracking()
            .Select(a => new SummaryRow(
                a.Id,
                a.ClientId,
                a.CreatedAt,
                a.Source,
                a.FixtureName,
                a.ResponseModel,
                a.AttentionLevel,
                a.InputFingerprint,
                db.AssessmentReviews
                    .Where(r => r.AssessmentId == a.Id)
                    .OrderByDescending(r => r.CreatedAt)
                    .ThenByDescending(r => r.Id)
                    .FirstOrDefault()));

    private static AssessmentSummaryResponse ToSummary(SummaryRow row, bool isCurrent, bool isLatest) => new(
        row.Id,
        row.CreatedAt,
        row.Source,
        row.Source == AnalysisSource.Fixture,
        row.FixtureName,
        row.ResponseModel,
        row.AttentionLevel,
        isCurrent,
        isLatest,
        ReviewOutcome.Status(row.LatestReview),
        ReviewOutcome.ApprovedLevel(row.AttentionLevel, row.LatestReview),
        row.LatestReview is null ? null : ReviewOutcome.ToResponse(row.LatestReview));

    // Only the client's newest assessment can be reviewed; older ones are
    // read-only history. Reviews are appended, never edited or deleted.
    public async Task<ReviewSubmitResult> AddReviewAsync(
        int clientId, int assessmentId, CreateReviewRequest request, CancellationToken cancellationToken)
    {
        var assessment = await db.Assessments
            .AsNoTracking()
            .Where(a => a.Id == assessmentId && a.ClientId == clientId)
            .Select(a => new { a.Id, a.AttentionLevel })
            .SingleOrDefaultAsync(cancellationToken);

        if (assessment is null)
        {
            return new ReviewSubmitResult(ReviewSubmitStatus.NotFound);
        }

        if (await LatestAssessmentIdAsync(clientId, cancellationToken) != assessment.Id)
        {
            return new ReviewSubmitResult(ReviewSubmitStatus.NotLatest);
        }

        if (!ReviewRules.TryValidate(request, assessment.AttentionLevel, out var valid, out var errors))
        {
            return new ReviewSubmitResult(ReviewSubmitStatus.Invalid, Errors: errors);
        }

        var review = new AssessmentReview
        {
            AssessmentId = assessment.Id,
            CreatedAt = timeProvider.GetUtcNow(),
            Decision = valid.Decision,
            ReviewedAttentionLevel = valid.ReviewedAttentionLevel,
            Notes = valid.Notes,
            ReviewerName = valid.ReviewerName,
        };

        db.AssessmentReviews.Add(review);
        await db.SaveChangesAsync(cancellationToken);

        return new ReviewSubmitResult(ReviewSubmitStatus.Created, ReviewOutcome.ToResponse(review));
    }

    private Task<int?> LatestAssessmentIdAsync(int clientId, CancellationToken cancellationToken) =>
        db.Assessments
            .Where(a => a.ClientId == clientId)
            .OrderByDescending(a => a.CreatedAt)
            .ThenByDescending(a => a.Id)
            .Select(a => (int?)a.Id)
            .FirstOrDefaultAsync(cancellationToken);

    private async Task<string> CurrentFingerprintAsync(int clientId, CancellationToken cancellationToken) =>
        InputFingerprint.Compute(await db.Communications
            .AsNoTracking()
            .Where(c => c.ClientId == clientId)
            .ToListAsync(cancellationToken));

    private async Task<AssessmentResponse> ToResponseAsync(Assessment assessment, CancellationToken cancellationToken)
    {
        var current = await db.Communications
            .AsNoTracking()
            .Where(c => c.ClientId == assessment.ClientId)
            .ToListAsync(cancellationToken);

        var reviews = await db.AssessmentReviews
            .AsNoTracking()
            .Where(r => r.AssessmentId == assessment.Id)
            .OrderByDescending(r => r.CreatedAt)
            .ThenByDescending(r => r.Id)
            .ToListAsync(cancellationToken);

        var latestId = await LatestAssessmentIdAsync(assessment.ClientId, cancellationToken);

        var evidenceById = current
            .Where(c => assessment.AnalyzedCommunicationIds.Contains(c.Id))
            .ToDictionary(c => c.Id, c => new EvidenceResponse(c.Id, c.Type, c.OccurredAt, c.Subject));

        IReadOnlyList<SignalResponse> Signals(SignalKind kind) => assessment.Signals
            .Where(signal => signal.Kind == kind)
            .Select(signal => new SignalResponse(
                signal.Description,
                signal.EvidenceCommunicationIds.Where(evidenceById.ContainsKey).Select(id => evidenceById[id]).ToList()))
            .ToList();

        var isFixture = assessment.Source == AnalysisSource.Fixture;
        var latestReview = reviews.FirstOrDefault();

        return new AssessmentResponse(
            assessment.Id,
            assessment.ClientId,
            assessment.CreatedAt,
            assessment.Source,
            isFixture,
            assessment.FixtureName,
            assessment.RequestedModel,
            assessment.ResponseModel,
            assessment.Effort,
            Disclaimer(assessment.Source, assessment.ResponseModel ?? assessment.RequestedModel),
            assessment.Summary,
            assessment.AttentionLevel,
            Signals(SignalKind.Concern),
            Signals(SignalKind.Positive),
            assessment.AnalyzedCommunicationIds,
            InputFingerprint.Compute(current) == assessment.InputFingerprint,
            assessment.Id == latestId,
            ReviewOutcome.Status(latestReview),
            ReviewOutcome.ApprovedLevel(assessment.AttentionLevel, latestReview),
            reviews.Select(ReviewOutcome.ToResponse).ToList());
    }
}
