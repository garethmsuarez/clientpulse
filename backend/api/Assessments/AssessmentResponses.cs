using ClientPulse.Api.Analysis;
using ClientPulse.Api.Communications;

namespace ClientPulse.Api.Assessments;

public record AssessmentResponse(
    int Id,
    int ClientId,
    DateTimeOffset CreatedAt,
    AnalysisSource Source,
    bool IsFixture,
    string? FixtureName,
    string? RequestedModel,
    string? ResponseModel,
    string? Effort,
    string Disclaimer,
    string Summary,
    AttentionLevel AttentionLevel,
    IReadOnlyList<SignalResponse> Concerns,
    IReadOnlyList<SignalResponse> PositiveSignals,
    IReadOnlyList<int> AnalyzedCommunicationIds,
    bool IsCurrent,
    bool IsLatest,
    ReviewStatus ReviewStatus,
    AttentionLevel? ReviewerApprovedAttentionLevel,
    IReadOnlyList<ReviewResponse> Reviews)
{
    // Pure mapping, so it can be unit tested without a database.
    // currentCommunications: the client's communications as they are now.
    // reviews: this assessment's reviews, newest first.
    // Evidence only links to communications that were analyzed and still exist.
    public static AssessmentResponse From(
        Assessment assessment,
        IReadOnlyCollection<Communication> currentCommunications,
        IReadOnlyList<AssessmentReview> reviews,
        int? latestAssessmentId)
    {
        var evidenceById = currentCommunications
            .Where(c => assessment.AnalyzedCommunicationIds.Contains(c.Id))
            .ToDictionary(c => c.Id, c => new EvidenceResponse(c.Id, c.Type, c.OccurredAt, c.Subject));

        IReadOnlyList<SignalResponse> Signals(SignalKind kind) => assessment.Signals
            .Where(signal => signal.Kind == kind)
            .Select(signal => new SignalResponse(
                signal.Description,
                signal.EvidenceCommunicationIds.Where(evidenceById.ContainsKey).Select(id => evidenceById[id]).ToList()))
            .ToList();

        var latestReview = reviews.FirstOrDefault();

        return new AssessmentResponse(
            assessment.Id,
            assessment.ClientId,
            assessment.CreatedAt,
            assessment.Source,
            assessment.Source == AnalysisSource.Fixture,
            assessment.FixtureName,
            assessment.RequestedModel,
            assessment.ResponseModel,
            assessment.Effort,
            AssessmentDisclaimer.For(assessment.Source, assessment.ResponseModel ?? assessment.RequestedModel),
            assessment.Summary,
            assessment.AttentionLevel,
            Signals(SignalKind.Concern),
            Signals(SignalKind.Positive),
            assessment.AnalyzedCommunicationIds,
            InputFingerprint.Compute(currentCommunications) == assessment.InputFingerprint,
            assessment.Id == latestAssessmentId,
            ReviewOutcome.Status(latestReview),
            ReviewOutcome.ApprovedLevel(assessment.AttentionLevel, latestReview),
            reviews.Select(ReviewResponse.From).ToList());
    }
}

public record SignalResponse(string Description, IReadOnlyList<EvidenceResponse> Evidence);

public record EvidenceResponse(int CommunicationId, CommunicationType Type, DateTimeOffset OccurredAt, string Subject);

// ReviewerName is self-reported and unverified.
public record ReviewResponse(
    int Id,
    int AssessmentId,
    DateTimeOffset CreatedAt,
    ReviewDecision Decision,
    AttentionLevel? ReviewedAttentionLevel,
    string? Notes,
    string ReviewerName)
{
    public static ReviewResponse From(AssessmentReview review) => new(
        review.Id,
        review.AssessmentId,
        review.CreatedAt,
        review.Decision,
        review.ReviewedAttentionLevel,
        review.Notes,
        review.ReviewerName);
}

public record AssessmentSummaryResponse(
    int Id,
    DateTimeOffset CreatedAt,
    AnalysisSource Source,
    bool IsFixture,
    string? FixtureName,
    string? ResponseModel,
    AttentionLevel AttentionLevel,
    bool IsCurrent,
    bool IsLatest,
    ReviewStatus ReviewStatus,
    AttentionLevel? ReviewerApprovedAttentionLevel,
    ReviewResponse? LatestReview);

// Shown with every assessment so fixture output is never mistaken for real inference.
public static class AssessmentDisclaimer
{
    public const string Fixture =
        "Fixture result: predefined for a synthetic demo scenario. Not produced by AI or any real analysis.";

    public static string For(AnalysisSource source, string? model) => source == AnalysisSource.Fixture
        ? Fixture
        : $"AI-generated by {model ?? "an AI model"}. May be inaccurate; review before relying on it. Synthetic data only.";
}
